"""Replace the current baseline offline. Dry run by default; no historical archives."""
from __future__ import annotations

import argparse
from collections import Counter
import csv
from copy import deepcopy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import baseline

# Fresh result inputs have a small explicit schema. Private provider responses,
# account IDs, receipts and execution logs are never copied into the companion.
FIELDS = {"case_id", "model", "input_hash", "status", "prediction", "probabilities",
          "latency_ms", "billed_cost_usd", "requested_model", "model_revision",
          "timing_included", "timing_class"}
CONFIG_FIELDS = {"backend", "kind", "model_id", "revision", "gpu", "max_input_tokens",
                 "dtype", "version", "specialist", "input_fit_recovery",
                 "native_probability_precision"}
CSV_FIELDS = ["case_id", "model", "status", "prediction", "input_hash", "latency_ms",
              "billed_cost_usd", "inference_cost_usd", "gateway_fee_usd",
              "configuration_id", "reused_result", "timing_included"]


def dump(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def config_id(config):
    return hashlib.sha256(json.dumps(config, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def merge_results(questions, old_rows, old_models, rows, configurations):
    """Only replace all eight self-hosted models; preserve all five APIs exactly."""
    selected = {m for m, info in old_models.items() if info["serving"] == "self-hosted"}
    if len(selected) != 8 or set(configurations) != selected:
        raise ValueError("Supply configurations for exactly the eight self-hosted models")
    if {r.get("model") for r in rows} != selected:
        raise ValueError("Supply results for exactly the eight self-hosted models; omit variants and APIs")
    models = deepcopy(old_models)
    configs = {}
    for name, incoming in configurations.items():
        if set(incoming) - {"configuration", "gpu", "timing_percentile_method"}:
            raise ValueError("Unexpected model metadata")
        config = incoming["configuration"]
        if set(config) - CONFIG_FIELDS:
            raise ValueError("Unexpected configuration field")
        for field in ("model_id", "revision"):
            if not config.get(field) or config[field] != old_models[name]["configuration"].get(field):
                raise ValueError("Changed model checkpoint: " + name)
        if config.get("backend") != "modal" or not incoming.get("gpu") or config.get("gpu") != incoming["gpu"]:
            raise ValueError("Expected explicit matching Modal GPU metadata")
        method = incoming.get("timing_percentile_method", "nearest_rank")
        baseline.percentile([], .95, method)
        models[name].update(configuration=config, gpu=incoming["gpu"], timing_percentile_method=method)
        configs[config_id(config)] = config
    fresh = []
    for raw in rows:
        if set(raw) - FIELDS:
            raise ValueError("Unexpected result fields; export only the documented normalized schema")
        model = raw["model"]
        config = models[model]["configuration"]
        for field, wanted in (("requested_model", config["model_id"]), ("model_revision", config["revision"])):
            if raw.get(field) != wanted:
                raise ValueError("Missing or mismatched result model identity")
        row = dict(raw)
        row.update(configuration_id=config_id(config), reused_result=False,
                   probability_source="native_choice_distribution" if raw.get("probabilities") is not None else None)
        if row.get("timing_class") in {"first_forward", "first_forward_with_kernel_startup"} and row.get("timing_included", True):
            raise ValueError("Mark first-forward startup timing as timing_included=false")
        fresh.append(row)
    combined = [r for r in old_rows if r["model"] not in selected] + fresh
    baseline.validate(questions, combined, list(models))
    return sorted(combined, key=lambda r: (r["case_id"], r["model"])), models, configs


def seal(root):
    # The staging tree contains only previously inventoried public files plus
    # the files generated by this importer; never a .local or Git directory.
    audited = set(json.loads((root / "MANIFEST.json").read_text())["sha256"])
    hashes = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError("Symlink in candidate release")
        if path.is_file() and path.name != "MANIFEST.json":
            relative = path.relative_to(root)
            known_workflow = str(relative) in audited and relative.parts[:2] == (".github", "workflows")
            if not known_workflow and any(p.startswith(".") and p not in {".gitignore", ".dockerignore"} for p in relative.parts):
                raise ValueError("Private file in staging tree")
            hashes[str(relative)] = baseline.sha256(path)
    dump(root / "MANIFEST.json", {"scope": "Research companion file inventory", "sha256": hashes})


def stage_replacement(root, stage, rows, models, source_hashes):
    manifest = json.loads((root / "MANIFEST.json").read_text())
    for name in list(manifest["sha256"]) + ["MANIFEST.json"]:
        target = stage / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / name, target)
    questions, old_rows, old_models = baseline.load_bundle(root)
    combined, current_models, new_configs = merge_results(questions, old_rows, old_models, rows, models)
    configs = json.loads((root / "configs/result_configurations.json").read_text())
    configs.update(new_configs)
    used = {r["configuration_id"] for r in combined}
    dump(stage / "configs/result_configurations.json", {key: configs[key] for key in sorted(used)})
    dump(stage / "configs/models.json", current_models)
    (stage / "results/baseline_predictions.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in combined))
    with (stage / "results/baseline_predictions.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=CSV_FIELDS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(combined)
    summary = baseline.summarize(questions, combined, current_models)
    baseline.write_summaries(summary, stage / "summaries")
    dump(stage / "reference/expected_metrics.json", summary)
    status = json.loads((stage / "release_status.json").read_text())
    status.pop("results_notice", None)
    status.update(results_temporary=False,
                  outcome_counts=dict(Counter(r["status"] for r in combined)))
    dump(stage / "release_status.json", status)
    provenance = json.loads((stage / "provenance.json").read_text())
    # Retain question provenance. Superseded result hashes are not a public archive.
    provenance["sources"] = {k: v for k, v in provenance["sources"].items() if k in {"cases.jsonl", "preflight.json"}}
    provenance["current_results"] = {"replacement_source_sha256": source_hashes,
        "replaced_models": sorted(models), "retained_models": [m for m in current_models if m not in models],
        "reference_kind": "Tables regenerated from validated current per-question records; not an independent replication."}
    dump(stage / "provenance.json", provenance)
    spec = importlib.util.spec_from_file_location("rebuild_current_pages", stage / "tools/rebuild_pages.py")
    pages = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pages)
    pages.main()
    seal(stage)
    baseline.load_bundle(stage)
    baseline.verify_reference(summary, json.loads((stage / "reference/expected_metrics.json").read_text()))
    return summary


def replace(root, predictions, configurations, *, apply=False):
    root, predictions, configurations = map(Path, (root, predictions, configurations))
    # Validate current checksums before copying or changing anything.
    baseline.load_bundle(root)
    source_hashes = {"predictions": baseline.sha256(predictions), "configurations": baseline.sha256(configurations)}
    rows = baseline.read_jsonl(predictions)
    models = json.loads(configurations.read_text())
    with tempfile.TemporaryDirectory(prefix="judgment-current-") as folder:
        stage = Path(folder) / "candidate"
        stage.mkdir()
        summary = stage_replacement(root, stage, rows, models, source_hashes)
        if apply:
            # Backups are transient outside the repository and removed on exit.
            # No superseded dataset is retained in the public tree or Git history.
            backup = Path(folder) / "rollback"
            names = [str(p.relative_to(stage)) for p in stage.rglob("*") if p.is_file()]
            names.sort(key=lambda n: n == "MANIFEST.json")  # install inventory last
            changed = []
            try:
                for name in names:
                    destination = root / name
                    if destination.exists() and destination.read_bytes() == (stage / name).read_bytes():
                        continue
                    saved = backup / name
                    if destination.exists():
                        saved.parent.mkdir(parents=True, exist_ok=True)
                        shutil.copyfile(destination, saved)
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    changed.append(name)
                    # Stage is in the OS temporary directory, so copy before
                    # replace to keep the final rename on the same filesystem.
                    temporary = destination.with_name(destination.name + ".replacing")
                    try:
                        shutil.copyfile(stage / name, temporary)
                        os.replace(temporary, destination)
                    finally:
                        temporary.unlink(missing_ok=True)
                baseline.load_bundle(root)
            except Exception:
                for name in reversed(changed):
                    if (backup / name).exists():
                        shutil.copyfile(backup / name, root / name)
                    else:
                        (root / name).unlink(missing_ok=True)
                raise
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--predictions", type=Path, required=True)
    parser.add_argument("--configurations", type=Path, required=True)
    parser.add_argument("--apply", action="store_true", help="Replace current files after validating the full candidate")
    args = parser.parse_args()
    summary = replace(ROOT, args.predictions, args.configurations, apply=args.apply)
    print(("Replaced current data" if args.apply else "Dry run passed; current data unchanged") +
          ": 8 × 1,005 replacement outcomes; 5 hosted models preserved; pages and summaries verified.")
    print("No old-result archive was created. No inference or publication was performed.")


if __name__ == "__main__":
    main()
